import assert from 'node:assert/strict';
import {build} from 'esbuild';
import {Miniflare} from 'miniflare';
import {readFile,readdir} from 'node:fs/promises';
await build({stdin:{contents:"export * from './lib/integrations';",resolveDir:process.cwd()},outfile:'outputs/automatic-estimate-test.mjs',bundle:true,platform:'node',format:'esm'});
const api=await import('../outputs/automatic-estimate-test.mjs');
const mf=new Miniflare({modules:true,script:'export default {fetch(){return new Response("test")}}',d1Databases:['DB']});
try {
 const db=await mf.getD1Database('DB');
 const sql=await readFile('drizzle/'+(await readdir('drizzle')).find(n=>n.endsWith('.sql')),'utf8');
 for(const s of sql.split('--> statement-breakpoint').map(s=>s.trim()).filter(Boolean))await db.prepare(s).run();
 const now=new Date().toISOString();
 await db.prepare('INSERT INTO school VALUES (1,?,?)').bind('test',JSON.stringify({minQuotes:1})).run();
 const item={name:'Assento sanitário Modelo Alfa',spec:'Branco',unit:'un',quantity:5};
 const request={id:'request',status:'estimating',version:1,items:[item],quotes:[]};
 await db.prepare('INSERT INTO records VALUES (?,?,?,1)').bind(request.id,'request',JSON.stringify(request)).run();
 await api.tick(db,{},now);const job=await api.claimJob(db,{},now,false);
 assert.deepEqual(job.item,item,'research carries exact requested item');
 const source={title:'Assento sanitário Modelo Alfa branco',url:'https://example.com/product',description:'Fonte fictícia'};
 const analysis={status:'verified',sourceUrl:source.url,productName:source.title,productQuote:source.title,priceAmount:129.9,currency:'BRL',priceType:'total',priceQuote:'Preço R$ 129,90',packageQuantity:1,unit:'un',unitQuote:'Por unidade.',itemMatches:true,unitMatches:true,reason:'Produto, cor e unidade correspondem ao pedido.'};
 const result={jobId:job.id,leaseToken:job.leaseToken,outcome:'success',sources:[source],browserResearch:{state:'ready',detail:'Sessão de teste',profile:'compras',checkedAt:now},priceEvidence:{origin:'authenticated_browser',analysis,url:source.url,title:source.title,text:source.title+'\nPreço R$ 129,90\nPor unidade.'}};
 await api.completeJob(db,result,now);
 let saved=(await api.rows(db,'request'))[0];
 assert.equal(saved.status,'admin_review');assert.equal(saved.estimate.total,649.5);
 assert.equal(saved.estimate.method,'automatic');assert(saved.estimate.notes.includes('navegador autenticado'));assert.equal(saved.estimate.freightKnown,false);
 assert.equal(saved.generalApproval,undefined);assert.equal(saved.quotes.length,0);
 const version=saved.version;await api.completeJob(db,result,now);await api.tick(db,{},now);
 saved=(await api.rows(db,'request'))[0];assert.equal(saved.version,version,'no repeat transition');
 const oldEstimate=JSON.stringify(saved.estimate);
 const late={...request,id:'late',items:[{...item,name:'Assento sanitário Modelo Beta'}]};
 await db.prepare('INSERT INTO records VALUES (?,?,?,1)').bind(late.id,'request',JSON.stringify(late)).run();
 await api.tick(db,{},now);const lateJob=await api.claimJob(db,{},now,false);
 const edited={...late,items:[{...item,name:'Assento sanitário Modelo Gama'}]};
 await db.prepare('UPDATE records SET data=?,version=version+1 WHERE id=?').bind(JSON.stringify(edited),late.id).run();
 await api.completeJob(db,{...result,jobId:lateJob.id,leaseToken:lateJob.leaseToken,priceEvidence:{...result.priceEvidence,analysis:{...analysis,productQuote:'Assento sanitário Modelo Beta branco',priceQuote:'Preço R$ 99,90',priceAmount:99.9},title:'Assento sanitário Modelo Beta branco',text:'Assento sanitário Modelo Beta branco\nPreço R$ 99,90\nPor unidade.'}},now);
 const pending=(await api.rows(db,'request')).find(r=>r.id==='late');
 assert.equal(pending.status,'estimating');assert.equal(pending.estimate,undefined,'stale item result cannot fill estimate');
 assert.equal(JSON.stringify((await api.rows(db,'request')).find(r=>r.id==='request').estimate),oldEstimate);
 const legacy={...request,id:'legacy-analysis'};
 await db.prepare('INSERT INTO records VALUES (?,?,?,1)').bind(legacy.id,'request',JSON.stringify(legacy)).run();
 await api.enqueueSearch(db,legacy,'test',now);
 const legacyJob=(await api.rows(db,'integration_job')).find(j=>j.requestId===legacy.id);
 await db.prepare('UPDATE records SET data=? WHERE id=?').bind(JSON.stringify({...legacyJob,state:'review',sources:[source]}),legacyJob.id).run();
 await api.enqueueSearch(db,legacy,'test',now);
 assert.equal((await api.rows(db,'integration_job')).find(j=>j.id===legacyJob.id).state,'queued','old bridge result without agent analysis is reprocessed');
 console.log('Automatic estimate: item snapshot, verified source, quantities, administrative review and replay passed.');
}finally{await mf.dispose();}
